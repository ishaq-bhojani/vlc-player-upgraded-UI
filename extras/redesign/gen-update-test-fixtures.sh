#!/usr/bin/env bash
#
# Regenerates modules/gui/qt/tests/update_channel_fixtures.h, the data of the
# test_qt_update_channel unit test: throwaway DSA-2048 keys (made here, in a
# temporary GNUPGHOME, never the owner's keyring) and a status file and a fake
# installer signed with them. The status file and its signature come from
# extras/redesign/make-status.sh itself, so the test covers what the release
# workflow produces.
#
#   extras/redesign/gen-update-test-fixtures.sh [OUT.h]
#
# Needs gpg. The keys are random: a regenerated header differs from the committed
# one, which is fine (the test only needs a consistent set); regenerate only when
# make-status.sh changes the format or the test needs more data.

set -euo pipefail

die() { echo "gen-update-test-fixtures.sh: $*" >&2; exit 1; }

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="${1:-$REPO/modules/gui/qt/tests/update_channel_fixtures.h}"
command -v gpg >/dev/null || die "gpg not found"

W="$(mktemp -d)"
chmod 700 "$W"
trap 'for h in "$W"/gnupg-*; do gpgconf --homedir "$h" --kill gpg-agent >/dev/null 2>&1 || true; done; rm -rf "$W"' EXIT

# one throwaway key per home: $1 = name, prints nothing, leaves $W/$1.pub.asc and $W/$1.sec.asc
mkkey() {
    local h="$W/gnupg-$1"
    mkdir "$h"; chmod 700 "$h"
    local g=(gpg --homedir "$h" --batch --no-tty --pinentry-mode loopback --passphrase "")
    "${g[@]}" --quick-gen-key "Throwaway update test key $1 <$1@invalid>" dsa2048 sign never >/dev/null 2>&1
    "${g[@]}" --armor --export > "$W/$1.pub.asc"
    "${g[@]}" --armor --export-secret-keys > "$W/$1.sec.asc"
    "${g[@]}" --list-keys --with-colons | awk -F: '$1=="fpr"{print $10; exit}' > "$W/$1.fpr"
}
mkkey a
mkkey b

printf 'Reborn test release\nSecond line of the notes\n' > "$W/notes.txt"
seq -s " " 1 400 > "$W/installer.exe"          # fake installer, plain text so it can live in a C string

mkdir "$W/out-a" "$W/out-b"
MAKE_STATUS_ALLOW_ANY_KEY=1 UPDATE_GPG_KEY="$(cat "$W/a.sec.asc")" UPDATE_GPG_PASSPHRASE="" \
    bash "$REPO/extras/redesign/make-status.sh" 7 https://example.invalid/vlc-reborn-7.exe \
        "$W/notes.txt" "$W/out-a" "$W/installer.exe" >/dev/null
MAKE_STATUS_ALLOW_ANY_KEY=1 UPDATE_GPG_KEY="$(cat "$W/b.sec.asc")" UPDATE_GPG_PASSPHRASE="" \
    bash "$REPO/extras/redesign/make-status.sh" 7 https://example.invalid/vlc-reborn-7.exe \
        "$W/notes.txt" "$W/out-b" >/dev/null
cmp -s "$W/out-a/status-win-x64" "$W/out-b/status-win-x64" || die "status files differ"

# the same status file signed with SHA-512 (a gpg configured with another default digest)
HA="$W/gnupg-a"
gpg --homedir "$HA" --batch --no-tty --pinentry-mode loopback --passphrase "" \
    --digest-algo SHA512 --armor --detach-sign --output "$W/status512.asc" "$W/out-a/status-win-x64" >/dev/null 2>&1

lit() {   # lit <file>: the file as C string literal lines
    sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/    "/' -e 's/$/\\n"/' "$1"
}
longid() { local f; f="$(cat "$1")"; local k="${f: -16}" o="" i; for i in 0 2 4 6 8 10 12 14; do o+="0x${k:$i:2}, "; done; printf '%s' "${o%, }"; }

{
cat <<EOF
/* GENERATED by extras/redesign/gen-update-test-fixtures.sh - throwaway keys, no secret
 * (the private keys were discarded). Used by test_update_channel.c. */

/* key A: signs the status file and the installer; key B: another signer */
static const uint8_t fixture_key_a_longid[8] = { $(longid "$W/a.fpr") };
static const uint8_t fixture_key_b_longid[8] = { $(longid "$W/b.fpr") };

static const uint8_t fixture_key_a[] = {
$(lit "$W/a.pub.asc")
};

/* make-status.sh 7 https://example.invalid/vlc-reborn-7.exe: what update.c parses */
static const char fixture_status[] =
$(lit "$W/out-a/status-win-x64");

/* detached signatures of fixture_status, "gpg --armor --detach-sign" */
static const uint8_t fixture_status_sig_a[] = {
$(lit "$W/out-a/status-win-x64.asc")
};
static const uint8_t fixture_status_sig_a_sha512[] = {
$(lit "$W/status512.asc")
};
static const uint8_t fixture_status_sig_b[] = {
$(lit "$W/out-b/status-win-x64.asc")
};

/* fake installer (seq -s " " 1 400) and its signature by key A: <installer>.asc */
static const char fixture_installer[] =
$(lit "$W/installer.exe");
static const uint8_t fixture_installer_sig_a[] = {
$(lit "$W/out-a/installer.exe.asc")
};
EOF
} > "$OUT"

echo "gen-update-test-fixtures.sh: wrote $OUT"
