#!/usr/bin/env python3
"""Generate the redesign icon font with upstream's makeIconFont.py.

    cd modules/gui/qt/redesign/assets
    python3 ../../../../../extras/redesign/make_icon_font.py VLCIconsRedesign.json

Run extras/redesign/build_icons.py first (it writes VLCIconsRedesign.json and icons/*.svg). Needs
fontforge (Debian: python3-fontforge); see docs/redesign/tokens.md, section Icons, for the container
command.

Outputs, all paths come from the JSON model:
  VLCIconsRedesign.ttf   next to the JSON (registered in redesign_assets.qrc)
  ../../style/vlcicons.hpp   header with every glyph: upstream's names at their upstream code points,
                             then the rd_* glyphs (generated by makeIconFont.py unchanged)
  ../../style/vlcicons.cpp   the constructor, which picks the font: the stock VLCIcons.ttf, or
                             VLCIconsRedesign.ttf once redesign::useRedesignIconFont() was called
                             (qt.cpp does that when qt-redesign is on). This is the only part that
                             differs from makeIconFont.py's own output, hence this wrapper.

Both fonts use the family name "VLCIcons" (VLCIcons.fontFamily), and only one of them is ever loaded.
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
UPSTREAM = os.path.join(HERE, "..", "..", "modules", "gui", "qt", "pixmaps", "makeIconFont.py")


def render_cpp(*, qml_prefix, font_file, **kwargs):
    return f"""
/**
 * This file was generated by makeIconFont.py through extras/redesign/make_icon_font.py,
 * please do not edit by hand
 */
#include <QFontDatabase>
#include <QQmlFile>
#include "vlcicons.hpp"
#include "redesign/cpp/iconfont.hpp"

VLCIcons::VLCIcons(QObject* parent)
    : QObject(parent)
{{
    // stock mode loads upstream's font, qt-redesign the redesign font (same family name)
    const QString url = redesign::iconFontEnabled()
        ? QStringLiteral("{qml_prefix}{font_file}")
        : QStringLiteral("qrc:///VLCIcons.ttf");
    QFontDatabase::addApplicationFont(QQmlFile::urlToLocalFileOrQrc(url));
}}"""


def main(argv):
    spec = importlib.util.spec_from_file_location("makeIconFont", UPSTREAM)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.renderCpp = render_cpp
    import argparse
    parser = argparse.ArgumentParser(description="generate the redesign icon font")
    parser.add_argument("model", type=argparse.FileType("r"))
    args = parser.parse_args(argv[1:])
    module.main(args.model)


if __name__ == "__main__":
    main(sys.argv)
