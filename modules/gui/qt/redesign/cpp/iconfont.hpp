#ifndef VLC_QT_REDESIGN_ICONFONT_HPP
#define VLC_QT_REDESIGN_ICONFONT_HPP

namespace redesign
{

namespace detail
{
inline bool& iconFontFlag()
{
    static bool enabled = false;
    return enabled;
}
} // namespace detail

/**
 * Makes the VLCIcons singleton load the redesign icon font (":/redesign/VLCIconsRedesign.ttf")
 * instead of upstream's VLCIcons.ttf. Both have the family name "VLCIcons" and the same code
 * points for upstream's glyphs. Call it before the QML engine creates the singleton; the
 * constructor in style/vlcicons.cpp (generated by extras/redesign/make_icon_font.py) reads it.
 */
inline void useRedesignIconFont()
{
    detail::iconFontFlag() = true;
}

inline bool iconFontEnabled()
{
    return detail::iconFontFlag();
}

} // namespace redesign

#endif // VLC_QT_REDESIGN_ICONFONT_HPP
