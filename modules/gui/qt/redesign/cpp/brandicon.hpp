#ifndef VLC_QT_REDESIGN_BRANDICON_HPP
#define VLC_QT_REDESIGN_BRANDICON_HPP

#include <QIcon>
#include <QString>

namespace redesign
{

/**
 * Application icon of the product (window, taskbar, tray, About): the Vireo icon in every
 * size of the bundled PNG set (assets/brand/png, generated by extras/redesign/make-icons.sh
 * from the SVG master), so the shell picks the sharpest one. Callers use it only when
 * redesign::isEnabled(); stock mode (qt-redesign=false) keeps the upstream icon.
 */
inline QIcon appIcon()
{
    QIcon icon;
    for (int size : { 16, 24, 32, 48, 64, 128, 256 })
        icon.addFile(QStringLiteral(":/redesign/brand/vireo-%1.png").arg(size), QSize(size, size));
    return icon;
}

} // namespace redesign

#endif // VLC_QT_REDESIGN_BRANDICON_HPP
